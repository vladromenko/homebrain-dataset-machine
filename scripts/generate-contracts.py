"""Regenerate wire schemas and TypeScript from the canonical Pydantic definitions."""
import json
import types
from pathlib import Path
from typing import get_args, get_origin, Literal, Union, Any
import sys
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT))
from homebrain.lab import contracts

MODELS = ['RobotCapability','ProjectDescriptor','TaskCard','ActionRequest','ActionResult','SessionSnapshot','Progress','LabEvent']
ROOT = Path(__file__).resolve().parents[1]


def ts(annotation):
    origin, args = get_origin(annotation), get_args(annotation)
    primitives = {str:'string', int:'number', float:'number', bool:'boolean', type(None):'null', Any:'unknown'}
    if annotation in primitives:
        return primitives[annotation]
    if origin is Literal:
        return ' | '.join(json.dumps(value) for value in args)
    if origin in (Union, types.UnionType):
        return ' | '.join(ts(value) for value in args)
    if origin is list:
        return '('+ts(args[0])+')[]'
    if origin is dict:
        return 'Record<string, '+ts(args[1])+ '>'
    return 'unknown'


def generate():
    lines = ['// Generated by scripts/generate-contracts.py; do not edit.']
    for name in MODELS:
        model = getattr(contracts, name)
        (ROOT/'contracts'/(name+'.schema.json')).write_text(json.dumps(model.model_json_schema(),indent=2)+'\n')
        lines.append('export interface '+name+' {')
        lines.extend('  '+key+': '+ts(field.annotation)+';' for key, field in model.model_fields.items())
        lines.append('}\n')
    (ROOT/'frontend/src/lib/generated.ts').write_text('\n'.join(lines))
    document = {'openapi':'3.1.0', 'info':{'title':'Homebrain Lab contract components','version':'homebrain.lab.v1',
        'description':'Canonical component schemas; native APIs retain their own definitions.'}, 'paths':{},
        'components':{'schemas':{name:getattr(contracts,name).model_json_schema() for name in MODELS}}}
    (ROOT/'contracts/openapi.json').write_text(json.dumps(document,indent=2)+'\n')


if __name__ == '__main__':
    generate()
